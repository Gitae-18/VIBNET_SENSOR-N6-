static HAL_StatusTypeDef LIN1_Test_SendFrame(void)
{
  static const uint8_t frame[] =
  {
    0x55U,                         /* Sync */
    0x52U,                         /* Protected ID for LIN ID 0x12 */
    0x11U, 0x22U, 0x33U, 0x44U,   /* Data 0..3 */
    0x55U, 0x66U, 0x77U, 0x88U,   /* Data 4..7 */
    0x47U                          /* Enhanced checksum */
  };

  if (HAL_LIN_SendBreak(&huart2_lin_test) != HAL_OK)
  {
    return HAL_ERROR;
  }

  return HAL_UART_Transmit(&huart2_lin_test, (const uint8_t *)frame,
                           (uint16_t)sizeof(frame), 100U);
}
